"""Compact rescue demo: a small, explicitly AUTHORED world for a visible end-to-end rescue loop.

This is not a random seeded scenario and not upstream terrain. It pins a few world-truth
outcomes (one damaged, occupied building next to the staging area; one trapped and one
immobile occupant) so that a short run can show the whole agent loop:
search -> detection -> report -> task generation -> allocation -> specialist extrication ->
loading -> transport -> receiver acknowledgment at a medical station.

What stays honest:
  * the pinned occupants are world truth only; agents start without them and must discover
    them through the scripted interior-search model (A008) and their own reports;
  * every task is generated by agents from their beliefs; allocation, messages and action
    outcomes run through the normal runtime and kernel (they can still fail or be delayed);
  * pinned truth is written with cause "authored_demo" and labelled as such.
"""
