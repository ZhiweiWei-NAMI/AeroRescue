STATE_MACHINES: dict[str, dict] = _build_state_machines()


def reachable(key: str, before: Any, after: Any) -> bool:
    """Belief check: an agent may learn a later state without observing the intermediate ones,
    so a belief change is valid when ``after`` is reachable from ``before`` through the machine.
    World/task/action transitions still use the strict single-edge :func:`validate`."""
    if validate(key, before, after):
        return True
    machine = STATE_MACHINES.get(key)
    if machine is None or before not in machine["states"] or after not in machine["states"]:
        return False
    seen, frontier = {before}, [before]
    while frontier:
        state = frontier.pop()
        for source, target, _via in machine["transitions"]:
            if source == state and target not in seen:
                if target == after:
                    return True
                seen.add(target)
                frontier.append(target)
    return False


def validate(key: str, before: Any, after: Any) -> bool:
    """Fail closed: only explicitly listed state pairs are transitions.

    Initial declarations (before=None) are not transitions. The kernel should
    distinguish declarations from changes and mark invalid changes, not crash.
    This predicate does not validate action provenance: its frozen API has no via.
    """
    if not isinstance(key, str) or not isinstance(before, str) or not isinstance(after, str):
        return False
    machine = STATE_MACHINES.get(key)
    if machine is None or before not in machine["states"] or after not in machine["states"]:
        return False
    return any(source == before and target == after
               for source, target, _via in machine["transitions"])


