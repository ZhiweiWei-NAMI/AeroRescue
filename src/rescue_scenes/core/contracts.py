def write_schemas(dir: str | Path | None = None) -> None:
    """Write the nine authoritative schemas, without importing generated JSON.

    File names are upstream-semantics.schema.json, env-config.schema.json, etc.
    The versioned schema identifiers remain the keys of JSON_SCHEMAS.
    """
    target = Path(dir) if dir is not None else Path(__file__).with_name("schemas")
    target.mkdir(parents=True, exist_ok=True)
    for name, schema in JSON_SCHEMAS.items():
        filename = name.split("/", 1)[0].removeprefix("rescue.") + ".schema.json"
        (target / filename).write_text(
            json.dumps(schema, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
